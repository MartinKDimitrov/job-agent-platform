"""Dump the ESCO taxonomy skills into a static data file the canon dictionary merges at import,
so a profile's Bulgarian skill ("амортизация") and an English JD ("depreciation") collapse to one
canonical skill — coverage then works across languages and real skills are pulled from non-tech
prose. Static (not a runtime DB dependency): re-run when the taxonomy changes.

    python -m app.tools.dump_esco_skills   # writes app/domain/esco_skills_data.py
"""
import os

from sqlalchemy import select

from ..data.db import SessionLocal
from ..data.models import TaxonomySkill

OUT = os.path.join(os.path.dirname(__file__), "..", "domain", "esco_skills_data.py")

# transversal / generic ESCO skills that would over-match ("communication" is in every JD) — a
# coverage signal that proves nothing. Dropped so they don't pollute extract_skills.
_GENERIC = {
    "communication", "teamwork", "work in a team", "leadership", "problem solving",
    "problem-solving", "creativity", "adaptability", "flexibility", "time management",
    "attention to detail", "critical thinking", "decision making", "organisational skills",
    "interpersonal skills", "analytical skills", "self-motivation", "work independently",
    "manage time", "show responsibility", "adapt to change", "think analytically",
    "use a computer", "computer literacy", "customer service", "multitasking", "negotiation",
    "presentation skills", "report writing", "microsoft office", "english", "public speaking",
}


def _keep(en: str) -> bool:
    e = en.lower().strip()
    return len(e) >= 4 and e not in _GENERIC and not e.isdigit()


def run(session_factory=SessionLocal) -> dict:
    data: dict[str, list[str]] = {}
    with session_factory() as db:
        for sk in db.execute(select(TaxonomySkill)).scalars():
            labels = sk.labels or {}
            en = (labels.get("en") or "").strip()
            if not en or not _keep(en):
                continue
            aliases = sorted({v.strip() for lang, v in labels.items()
                              if lang != "en" and v and v.strip().lower() != en.lower()
                              and len(v.strip()) >= 3})
            if en not in data:                       # first wins; skip exact-label duplicates
                data[en] = aliases
    with open(OUT, "w", encoding="utf-8") as f:
        f.write('"""ESCO skills → cross-language aliases. Generated by tools/dump_esco_skills.py."""\n')
        f.write("ESCO_SKILLS = {\n")
        for en in sorted(data):
            f.write(f"    {en!r}: {data[en]!r},\n")
        f.write("}\n")
    total_aliases = sum(len(v) for v in data.values())
    print(f"wrote {len(data)} skills, {total_aliases} aliases -> {os.path.abspath(OUT)}")
    return {"skills": len(data), "aliases": total_aliases}


if __name__ == "__main__":
    run()
